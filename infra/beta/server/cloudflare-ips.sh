#!/usr/bin/env bash
# The Cloudflare IP ranges, one list for Caddy and the firewall (run as root).
#
#   cloudflare-ips.sh update [--offline]   fetch, check, write, apply
#   cloudflare-ips.sh apply                 re-apply the current list
#   cloudflare-ips.sh show                  print the current list
#
# Source: https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6
# (--offline: the snapshot shipped in infra/beta/cloudflare/ips.txt).
# One list, three renderings:
#   /etc/athenos/cloudflare-ips.txt               the list (one CIDR per line)
#   /etc/caddy/cloudflare-trusted-proxies.caddy   `trusted_proxies static …`,
#                                                 imported by the Caddyfile
#   /etc/athenos/cloudflare-ips.nft               nftables sets (if you use
#                                                 firewall/nftables.conf)
# and the ufw rules "443/tcp from <range>" (comment cloudflare-443): new
# ranges are added before stale ones are removed, so 443 never closes.
# A list that looks wrong (too short, not CIDR) changes nothing.
# athenos-cloudflare-ips.timer runs `update` weekly.
set -euo pipefail

here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=common.sh
. "${ATHENOS_LIB_DIR:-$here}/common.sh"

: "${CF_LIST:=/etc/athenos/cloudflare-ips.txt}"
: "${CF_CADDY_SNIPPET:=/etc/caddy/cloudflare-trusted-proxies.caddy}"
: "${CF_NFT_SETS:=/etc/athenos/cloudflare-ips.nft}"
: "${CF_SNAPSHOT:=$here/../cloudflare/ips.txt}"
[ -f "$CF_SNAPSHOT" ] || CF_SNAPSHOT=/opt/athenos/current/infra/beta/cloudflare/ips.txt
UFW_COMMENT=cloudflare-443

[ "$(id -u)" = 0 ] || die "run as root (sudo)"

v4_re='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
v6_re='^[0-9a-f:]+::?[0-9a-f:]*/[0-9]{1,3}$'

fetch() { # -> candidate list on stdout
	if [ "${1:-}" = --offline ]; then
		grep -v '^#' -- "$CF_SNAPSHOT"
	else
		curl -fsS -m 20 https://www.cloudflare.com/ips-v4
		echo
		curl -fsS -m 20 https://www.cloudflare.com/ips-v6
		echo
	fi | tr -d '\r' | sed '/^$/d' | tr 'A-F' 'a-f' | LC_ALL=C sort -u
}

check_list() { # file
	local n4 n6 bad
	n4=$(grep -cE "$v4_re" "$1" || true)
	n6=$(grep -cE "$v6_re" "$1" || true)
	bad=$(grep -vE "$v4_re|$v6_re" "$1" || true)
	[ -z "$bad" ] || die "not a CIDR: $(printf '%s' "$bad" | head -n 3 | tr '\n' ' ')"
	[ "$n4" -ge 10 ] && [ "$n6" -ge 5 ] || die "suspicious list ($n4 IPv4, $n6 IPv6 ranges); nothing changed"
}

render_caddy() {
	local tmp
	tmp=$(mktemp)
	{
		echo "# Generated by cloudflare-ips.sh from $CF_LIST - do not edit."
		printf 'trusted_proxies static'
		tr '\n' ' ' <"$CF_LIST" | sed 's/ *$//; s/^/ /'
		echo
	} >"$tmp"
	install -d -m 0755 "$(dirname -- "$CF_CADDY_SNIPPET")"
	install -m 0644 "$tmp" "$CF_CADDY_SNIPPET"
	rm -f -- "$tmp"
	if command -v caddy >/dev/null 2>&1 && [ -f /etc/caddy/Caddyfile ] && systemctl is-active --quiet caddy; then
		caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 ||
			die "caddy validate failed with the new list; Caddy keeps running with the old one"
		systemctl reload caddy
		log "caddy reloaded with $(wc -l <"$CF_LIST" | tr -d ' ') trusted ranges"
	fi
}

render_nft() {
	{
		echo "# Generated by cloudflare-ips.sh - do not edit."
		echo "define CLOUDFLARE_V4 = { $(grep -E "$v4_re" "$CF_LIST" | paste -sd, - | sed 's/,/, /g') }"
		echo "define CLOUDFLARE_V6 = { $(grep -E "$v6_re" "$CF_LIST" | paste -sd, - | sed 's/,/, /g') }"
	} >"$CF_NFT_SETS"
	chmod 0644 "$CF_NFT_SETS"
	if systemctl is-active --quiet nftables 2>/dev/null; then
		nft -c -f /etc/nftables.conf && systemctl reload nftables && log "nftables reloaded"
	fi
}

apply_ufw() {
	command -v ufw >/dev/null 2>&1 || return 0
	ufw status | grep -q '^Status: active' || {
		log "ufw not active: firewall rules not changed"
		return 0
	}
	local cidr
	while IFS= read -r cidr; do
		ufw allow proto tcp from "$cidr" to any port 443 comment "$UFW_COMMENT" >/dev/null
	done <"$CF_LIST"
	# Remove rules of ranges that are no longer listed (highest number first).
	ufw status numbered | grep -- "# $UFW_COMMENT" |
		sed -E 's/^\[ *([0-9]+)\].* ([0-9a-fA-F:.]+\/[0-9]+) +# .*/\1 \2/' | sort -rn |
		while read -r num from; do
			if ! grep -qxF -- "$(printf '%s' "$from" | tr 'A-F' 'a-f')" "$CF_LIST"; then
				ufw --force delete "$num" >/dev/null
				log "ufw: removed stale range $from"
			fi
		done
	log "ufw: 443/tcp open for $(wc -l <"$CF_LIST" | tr -d ' ') Cloudflare ranges"
}

apply() {
	[ -s "$CF_LIST" ] || die "$CF_LIST missing; run: cloudflare-ips.sh update"
	render_caddy
	render_nft
	apply_ufw
}

case ${1:-} in
update)
	tmp=$(mktemp)
	trap 'rm -f -- "$tmp"' EXIT
	fetch "${2:-}" >"$tmp"
	check_list "$tmp"
	[ -d "$(dirname -- "$CF_LIST")" ] || die "$(dirname -- "$CF_LIST") missing (install.sh dirs)"
	if [ -f "$CF_LIST" ] && cmp -s "$tmp" "$CF_LIST"; then
		log "Cloudflare ranges unchanged ($(wc -l <"$CF_LIST" | tr -d ' '))"
	else
		[ ! -f "$CF_LIST" ] || diff -u "$CF_LIST" "$tmp" >&2 || true
		install -m 0644 "$tmp" "$CF_LIST"
		log "Cloudflare ranges written to $CF_LIST"
	fi
	apply
	;;
apply) apply ;;
show) cat -- "$CF_LIST" ;;
*)
	sed -n '2,22p' "$0"
	exit 1
	;;
esac
