check_out "--version NAME=…: name it too" "name athenos-webcomponents as a module too"

# --- 2. --dry-run changes nothing ---------------------------------------------------
ath="$root/modules/athenos"
head_before=$(git -C "$ath" rev-parse HEAD)
release "" --dry-run athenos
check_eq "dry run exits 0" 0 "$rc"
check_out "dry run: summary old -> new" "v0.13.0-10     -> v0.13.0-11"
check_out "dry run: files changed" "Cargo.toml Cargo.lock .fenrir-dev.toml"
check_out "dry run: says so" "Dry run: nothing is written"
check_eq "dry run: HEAD unchanged" "$head_before" "$(git -C "$ath" rev-parse HEAD)"
check_eq "dry run: worktree clean" "" "$(git -C "$ath" status --porcelain)"
check "dry run: no local tag" test ! -e "$ath/.git/refs/tags/v0.13.0-11"
check "dry run: no remote tag" sh -c "! git --git-dir '$remotes/athenos.git' rev-parse -q --verify refs/tags/v0.13.0-11"

# --- 3. the question: anything but yes rolls back ------------------------------------
release "n" athenos
check_eq "declined: exit 1" 1 "$rc"
check_out "declined: summary shown first" "Ready to push"
check_out "declined: one question" "Push 1 branch(es) and tag(s) to origin? [y/N]"
check_out "declined: not pushed" "Not pushed."
check_eq "declined: HEAD back" "$head_before" "$(git -C "$ath" rev-parse HEAD)"
check "declined: local tag removed" sh -c "! git -C '$ath' rev-parse -q --verify refs/tags/v0.13.0-11"
check_eq "declined: clean" "" "$(git -C "$ath" status --porcelain)"
check_eq "declined: remote unchanged" "$head_before" "$(remote_head athenos 0.1.0)"
release "" athenos
check_eq "no answer (EOF): exit 1" 1 "$rc"
check "no answer: no tag" sh -c "! git -C '$ath' rev-parse -q --verify refs/tags/v0.13.0-11"

# --- 4. a failing gate rolls back every module of the run -----------------------------
ns="$root/modules/notification-service"
ns_before=$(git -C "$ns" rev-parse HEAD)
export FAIL_GATE=1
release "y" athenos notification-service
unset FAIL_GATE
check "failing gate: exit != 0" test "$rc" != 0
check_out "failing gate: named" "athenos: gates failed"
check_out "failing gate: rolled back" "Local release commits and tags removed; nothing was pushed."
check_eq "failing gate: notification-service HEAD back" "$ns_before" "$(git -C "$ns" rev-parse HEAD)"
check "failing gate: notification-service tag removed" sh -c "! git -C '$ns' rev-parse -q --verify refs/tags/v0.11.0-1"
check_eq "failing gate: athenos files restored" "" "$(git -C "$ath" status --porcelain)"
check_eq "failing gate: notification-service clean" "" "$(git -C "$ns" status --porcelain)"
check_eq "failing gate: remote unchanged" "$ns_before" "$(remote_head notification-service 0.1.0)"

# --- 5. next build -----------------------------------------------------------------
release "y" athenos
check_eq "next build: exit 0" 0 "$rc"
check_out "next build: gates ran" "gates ok"
check "next build: remote tag" remote_has_tag athenos v0.13.0-11
check_eq "next build: annotated tag" tag "$(git --git-dir "$remotes/athenos.git" cat-file -t refs/tags/v0.13.0-11)"
