check_eq "next build: tag on the release commit" "$rel" "$(git --git-dir "$remotes/athenos.git" rev-parse 'refs/tags/v0.13.0-11^{commit}')"
check_eq "next build: commit message, no trailer" "chore(release): v0.13.0-11" "$(git --git-dir "$remotes/athenos.git" log -1 --format=%B "$rel" | sed '/^$/d')"
check_eq "next build: author" "Joel Furter <joel.furter@gmail.com>" "$(git --git-dir "$remotes/athenos.git" log -1 --format='%an <%ae>' "$rel")"
check_eq "next build: committer" "Joel Furter <joel.furter@gmail.com>" "$(git --git-dir "$remotes/athenos.git" log -1 --format='%cn <%ce>' "$rel")"
check_eq "next build: tagger" "Joel Furter <joel.furter@gmail.com>" "$(git --git-dir "$remotes/athenos.git" for-each-ref --format='%(taggername) %(taggeremail)' refs/tags/v0.13.0-11)"
check_eq "next build: exactly the version files" ".fenrir-dev.toml Cargo.lock Cargo.toml" "$(git --git-dir "$remotes/athenos.git" show --name-only --format= "$rel" | LC_ALL=C sort | tr '\n' ' ' | sed 's/ $//')"
check "next build: Cargo.toml" grep -qx 'version = "0.13.0-11"' "$ath/Cargo.toml"
check "next build: dependency requirement untouched" grep -qF 'helper = { version = "0.13.0-10" }' "$ath/Cargo.toml"
check_eq "next build: Cargo.lock, only the module's entry" "0.13.0-11 0.13.0-10" "$(sed -n 's/^version = "\(.*\)"/\1/p' "$ath/Cargo.lock" | tr '\n' ' ' | sed 's/ $//')"
check_eq "next build: .fenrir-dev.toml, [module] only" '"0.13.0-11" "untouched"' "$(sed -n 's/^version = \(.*\)/\1/p' "$ath/.fenrir-dev.toml" | tr '\n' ' ' | sed 's/ $//')"
check_out "next build: release line (no GitHub origin)" "athenos                v0.13.0-11 (origin is not on GitHub"
check_out "next build: depot line, the real CLI" "depot import github --product athenos --version <product-version> --repo athenos@v0.13.0-11 --from athenos-<prev>"
check_out "next build: depot line names what is not in the run" "(not in this run: athenos-api athenos-web notification-service; --from keeps their rules"
check_out "next build: deploy line with per-repo tags" "TAG_ATHENOS=v0.13.0-11"
check_out "next build: deploy line, fenrir's tag" "infra/beta/deploy.sh v0.12.0"

