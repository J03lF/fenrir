#!/usr/bin/env bash
# Sandbox test of infra/release/release.sh: fixture repositories under a
# temporary directory, each with a local bare repository as origin. Nothing
# touches GitHub or a real checkout; git runs with a throwaway global config.
#
#   release-test.sh              fixtures + the workflow lint of this repo
#   release-test.sh --real DIR   additionally: clone the q-rel checkouts of
#                                DIR (layout of worktrees/rel: athenos-contracts,
#                                modules/<repo>, fenrir) into bare remotes and
#                                run the first 0.13.0 release against them
#                                (--version 0.13.0 --no-gates --yes, then
#                                webcomponents on its own line), and lint
#                                their workflows
#
# Plain bash with assertions (no bats); works with the bash 3.2 of macOS.
set -uo pipefail

here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
script="$here/../release.sh"
repo_root=$(cd -- "$here/../../.." && pwd)
real_dir=""
if [ "${1:-}" = "--real" ]; then
	real_dir=${2:?--real needs the directory of the q-rel checkouts}
	real_dir=$(cd -- "$real_dir" && pwd)
fi

tmp=$(mktemp -d "${TMPDIR:-/tmp}/release-test.XXXXXX")
if [ -n "${RELEASE_TEST_KEEP:-}" ]; then
	echo "release-test: keeping $tmp"
else
	trap 'rm -rf -- "$tmp"' EXIT
fi
export GIT_CONFIG_GLOBAL="$tmp/gitconfig" GIT_CONFIG_NOSYSTEM=1
git config --global user.name "Fixture"
git config --global user.email "fixture@example.invalid"
git config --global init.defaultBranch main
git config --global advice.detachedHead false
unset RELEASE_ROOT RELEASE_AUTHOR_NAME RELEASE_AUTHOR_EMAIL GIT_DIR GIT_WORK_TREE

passed=0
failed=0
ok() { passed=$((passed + 1)); }
bad() {
	failed=$((failed + 1))
	printf 'FAIL %s\n' "$*" >&2
}
check() { # DESCRIPTION COMMAND...
	local d=$1
	shift
	if "$@" >/dev/null 2>&1; then ok; else bad "$d"; fi
}
check_eq() { # DESCRIPTION EXPECTED ACTUAL
	if [ "$2" = "$3" ]; then ok; else bad "$1: expected '$2', got '$3'"; fi
}
check_out() { # DESCRIPTION NEEDLE (in $out)
	if grep -qF -- "$2" "$out"; then ok; else bad "$1: '$2' not in output:$(sed 's/^/\n    | /' "$out" | tr -d '\n' | head -c 3000)"; fi
}
check_not_out() { # DESCRIPTION NEEDLE
	if grep -qF -- "$2" "$out"; then bad "$1: '$2' unexpectedly in output"; else ok; fi
}

out="$tmp/out"
rc=0
runs=0
conf="$tmp/modules.conf"
release() { # ANSWER ARGS... → $rc, $out
	local answer=$1
	shift
	rc=0
	printf '%s\n' "$answer" | RELEASE_CONFIG=$conf bash "$script" "$@" >"$out" 2>&1 || rc=$?
	runs=$((runs + 1))
	{ printf '\n### %d: release.sh %s (answer %s, exit %d)\n' "$runs" "$*" "${answer:-none}" "$rc"; cat "$out"; } >>"$tmp/transcript"
}

root="$tmp/root"
remotes="$tmp/remotes"
mkdir -p "$root" "$remotes"

# fixture NAME PATH BRANCH: the directory exists with its files; make it a
# repository, commit, create a bare origin and push the branch.
fixture() {
	local name=$1 dir="$root/$2" branch=$3
	git -C "$dir" init -q -b "$branch"
	git -C "$dir" add -A
	git -C "$dir" commit -q -m "initial $name"
	git init -q --bare "$remotes/$name.git"
	git -C "$dir" remote add origin "$remotes/$name.git"
	git -C "$dir" push -q origin "$branch"
	git -C "$dir" branch -q --set-upstream-to "origin/$branch"
}
tag_all() { # NAME PATH TAG... (lightweight and annotated mixed)
	local name=$1 dir="$root/$2"
	shift 2
	for t in "$@"; do git -C "$dir" tag -a "$t" -m "$t"; done
	git -C "$dir" push -q origin --tags
}
remote_head() { git --git-dir "$remotes/$1.git" rev-parse "refs/heads/$2"; }
remote_has_tag() { git --git-dir "$remotes/$1.git" rev-parse -q --verify "refs/tags/$2" >/dev/null; }
local_has_tag() { git -C "$root/$1" rev-parse -q --verify "refs/tags/$2" >/dev/null; }

cargo_fixture() { # PATH CRATE VERSION
	local dir="$root/$1"
	mkdir -p "$dir"
	cat >"$dir/Cargo.toml" <<TOML
[package]
name = "$2"
version = "$3"
edition = "2021"

[dependencies]
helper = { version = "$3" }
TOML
	cat >"$dir/Cargo.lock" <<LOCK
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "$2"
version = "$3"
dependencies = [
 "helper",
]

[[package]]
name = "helper"
version = "$3"
source = "registry+https://github.com/rust-lang/crates.io-index"
LOCK
	cat >"$dir/.fenrir-dev.toml" <<DEV
[module]
id = "$2"
version = "$3"

[dev]
version = "untouched"
DEV
}

